export type LegalDocKind = "privacy" | "terms";

export function getLegalDocument(
  kind: LegalDocKind,
  locale: "ar" | "he" | "en"
): { document: LegalDocument; contentLocale: "ar" | "he"; isEnglishFallback: boolean } {
  const useHebrew = locale === "he";
  if (kind === "privacy") {
    return {
      document: useHebrew ? privacyHe : privacyAr,
      contentLocale: useHebrew ? "he" : "ar",
      isEnglishFallback: locale === "en",
    };
  }
  return {
    document: useHebrew ? termsHe : termsAr,
    contentLocale: useHebrew ? "he" : "ar",
    isEnglishFallback: locale === "en",
  };
}
